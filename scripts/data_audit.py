"""Inventory every dataset (read straight from the zips) and write outputs/data_audit.md.

Usage: .venv/bin/python scripts/data_audit.py [--workers 4]
"""
from __future__ import annotations

import argparse
import collections
import json
import re
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import nibabel as nib
import numpy as np
import pandas as pd
from PIL import Image

from dentalpano import contact
from dentalpano import io as dio

OUT = dio.REPO / "outputs"
TF3_SET = {"P": "A", "F": "B", "S": "C"}


def tf3_case(case: str) -> dict:
    zf = dio.open_zip("toothfairy3")
    ih = dio.nifti_header(zf, f"imagesTr/{case}_0000.nii.gz")
    lab = dio.load_nifti(zf, f"labelsTr/{case}.nii.gz")
    counts = np.bincount(np.asarray(lab.dataobj).ravel())
    return {
        "case": case, "set": TF3_SET[case[11]],
        "shape": tuple(int(s) for s in ih.get_data_shape()),
        "label_shape": tuple(int(s) for s in lab.shape),
        "spacing": tuple(round(float(z), 4) for z in ih.get_zooms()),
        "img_dtype": str(ih.get_data_dtype()), "lab_dtype": str(lab.get_data_dtype()),
        "axcodes": "".join(nib.aff2axcodes(ih.get_best_affine())),
        "affine_match": bool(np.allclose(ih.get_best_affine(), lab.affine, atol=1e-3)),
        "label_counts": {int(i): int(c) for i, c in enumerate(counts) if c and i},
    }


def audit_tf3(workers: int) -> tuple[pd.DataFrame, dict]:
    zf = dio.open_zip("toothfairy3")
    labels = json.loads(zf.read("dataset.json"))["labels"]
    cases = sorted(n[len("labelsTr/"):-7] for n in zf.namelist()
                   if n.startswith("labelsTr/") and n.endswith(".nii.gz"))
    imgs = {n[len("imagesTr/"):-12] for n in zf.namelist() if n.startswith("imagesTr/") and n.endswith("_0000.nii.gz")}
    assert imgs == set(cases), "image/label case mismatch"
    with ProcessPoolExecutor(workers) as ex:
        rows = list(ex.map(tf3_case, cases, chunksize=4))
    return pd.DataFrame(rows), labels


def audit_tf2(tf3_cases: list[str]) -> pd.DataFrame:
    zf = dio.open_zip("toothfairy2")
    rows = []
    for n in sorted(zf.namelist()):
        m = re.search(r"(imagesTr|labelsTr)/ToothFairy2(\w)_(\d+)(_0000)?\.mha$", n)
        if not m:
            continue
        h = dio.mha_header(zf, n)
        rows.append({"kind": m[1], "case": f"ToothFairy2{m[2]}_{m[3]}", "letter": m[2],
                     "shape": tuple(int(v) for v in h["DimSize"].split()),
                     "spacing": tuple(round(float(v), 4) for v in h["ElementSpacing"].split()),
                     "orient": h.get("AnatomicalOrientation"), "etype": h["ElementType"]})
    df = pd.DataFrame(rows)
    df["tf3_case"] = df.case.str.replace("ToothFairy2", "ToothFairy3")
    df["in_tf3"] = df.tf3_case.isin(tf3_cases)
    return df


def audit_dentex() -> pd.DataFrame:
    rows = []
    for key in ("train_zip", "val_zip"):
        zf = dio.open_zip("dentex", key)
        for n in zf.namelist():
            if n.endswith(".png") and ".ipynb_checkpoints" not in n:
                w, h = Image.open(zf.open(n)).size
                rows.append({"zip": key, "subset": n.split("/")[1], "file": n, "w": w, "h": h})
    return pd.DataFrame(rows)


def dentex_annotations() -> dict:
    zf = dio.open_zip("dentex", "train_zip")
    out = {}
    for n in zf.namelist():
        if n.endswith(".json"):
            j = json.loads(zf.read(n))
            cat_keys = [k for k in j if k.startswith("categor")]
            out[n] = {"images": len(j["images"]), "annotations": len(j["annotations"]),
                      **{k: [c["name"] for c in j[k]] for k in cat_keys}}
    return out


def md_table(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False) if hasattr(df, "to_markdown") else df.to_string()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()
    OUT.mkdir(exist_ok=True)
    L = []

    # ---------------- ToothFairy3
    tf3, labels = audit_tf3(args.workers)
    tf3.to_csv(OUT / "audit_tf3.csv", index=False)
    id2name = {v: k for k, v in labels.items()}
    L += ["# Data audit", "", "Generated by `scripts/data_audit.py` (reads zips in place).", "",
          "## ToothFairy3", "", f"Cases: **{len(tf3)}**  ",
          "By set: " + ", ".join(f"{s} = {n}" for s, n in tf3.set.value_counts().sort_index().items()), ""]
    for col in ("spacing", "img_dtype", "lab_dtype", "axcodes", "affine_match"):
        vc = tf3[col].astype(str).value_counts()
        L.append(f"- **{col}**: " + "; ".join(f"`{k}` ×{v}" for k, v in vc.items()))
    L.append(f"- image/label shape mismatch: {(tf3['shape'] != tf3['label_shape']).sum()}")
    L += ["", "Volume size by set (voxels; field of view in mm at 0.3 mm):", "",
          "| set | n | axis0 min–med–max | axis1 min–med–max | axis2 min–med–max | median FOV mm |", "|---|---|---|---|---|---|"]
    for s, g in tf3.groupby("set"):
        sh = np.array(g["shape"].tolist())
        cells = [f"{a.min()}–{int(np.median(a))}–{a.max()}" for a in sh.T]
        fov = "×".join(f"{0.3 * np.median(a):.0f}" for a in sh.T)
        L.append(f"| {s} | {len(g)} | " + " | ".join(cells) + f" | {fov} |")
    L.append("")
    present = collections.Counter(i for d in tf3.label_counts for i in d)
    vox = collections.Counter()
    for d in tf3.label_counts:
        vox.update(d)
    L += ["", "### Label IDs", "",
          f"dataset.json lists {len(labels) - 1} foreground classes (max ID {max(labels.values())}). "
          f"IDs found in data: {len(present)}.", "",
          "| ID | name | #cases | % cases | A | B | C | median voxels |", "|---|---|---|---|---|---|---|---|"]
    for i in sorted(set(present) | {v for v in labels.values() if v}):
        has = tf3.label_counts.apply(lambda d: i in d)
        per = tf3[has].set.value_counts()
        med = int(np.median([d[i] for d in tf3.label_counts if i in d])) if present[i] else 0
        L.append(f"| {i} | {id2name.get(i, '**not in dataset.json**')} | {present[i]} | "
                 f"{100 * present[i] / len(tf3):.1f} | {per.get('A', 0)} | {per.get('B', 0)} | {per.get('C', 0)} | {med} |")
    empty = sorted(v for v in labels.values() if v and v not in present)
    unknown = sorted(i for i in present if i not in id2name)
    L += ["", f"Listed but never present: {empty or 'none'}",
          f"Present but not in dataset.json: {unknown} in " +
          ", ".join(sorted(tf3[tf3.label_counts.apply(lambda d: any(i in d for i in unknown))].case)) + " → treat as background."]

    # ---------------- ToothFairy2
    tf2 = audit_tf2(list(tf3.case))
    tf2.to_csv(OUT / "audit_tf2.csv", index=False)
    imgs2 = tf2[tf2.kind == "imagesTr"].merge(tf3[["case", "shape"]].rename(columns={"case": "tf3_case", "shape": "tf3_shape"}),
                                             on="tf3_case", how="left")
    ov = imgs2[imgs2.in_tf3]
    L += ["", "## ToothFairy2 vs ToothFairy3 overlap", "",
          f"TF2 cases (images): **{len(imgs2)}** (" + ", ".join(f"{k}: {v}" for k, v in imgs2.letter.value_counts().sort_index().items()) + ")",
          f"- TF2 labelsTr files: {(tf2.kind == 'labelsTr').sum()}",
          f"- spacing: " + "; ".join(f"`{k}` ×{v}" for k, v in imgs2.spacing.astype(str).value_counts().items()),
          f"- ElementType: " + "; ".join(f"`{k}` ×{v}" for k, v in imgs2.etype.value_counts().items()),
          f"- AnatomicalOrientation: " + "; ".join(f"`{k}` ×{v}" for k, v in imgs2.orient.value_counts().items()),
          f"- TF2 cases whose ID (letter+number) also exists in TF3: **{len(ov)}** "
          f"(" + ", ".join(f"{k}: {v}" for k, v in ov.letter.value_counts().sort_index().items()) + ")",
          f"- of those, identical volume shape in both: **{(ov['shape'] == ov['tf3_shape']).sum()} / {len(ov)}**",
          f"- TF2-only cases (not in TF3): {(~imgs2.in_tf3).sum()}",
          f"- TF3-only cases (not in TF2): {len(set(tf3.case) - set(imgs2.tf3_case))}",
          "", "Rule: TF3 supersedes TF2 for every overlapping ID; TF2-only cases are not used unless we decide otherwise."]

    # ---------------- CONTACT
    ct = contact.label_table()
    ct.to_csv(OUT / "audit_contact.csv", index=False)
    L += ["", "## CONTACT", "",
          "**Differs from the brief:** this copy contains 227×227 RGB crops around the lower third molar plus grayscale JPEG masks "
          "(no full 2700×1249 panoramics, no XML polygons). It also has `{train,test}ImageFeatures.xlsx`: ImageNum, 6 radiographic "
          "features (Obscuration, Deflection, NarrowingRoots, NarrowingCanal, DiscontinuityCanal, CanalDeviation), and binary `Class` (= contact).", "",
          md_table(ct.groupby(["split", "contact"]).size().rename("n").reset_index()), "",
          f"Contact = 1: **{(ct.contact == 1).sum()}**, contact = 0: **{(ct.contact == 0).sum()}** (brief: 1100 / 378 ✔).", "",
          "Mask encodings (auto-detected per mask): " + ", ".join(f"scheme {k}: {v}" for k, v in ct.scheme.value_counts().items())
          + " — A: molar 42 / canal 213 / overlap≈128; B: canal 85 / molar 170 / overlap 255.", "",
          f"Groups derived as contact→1, else mask overlap ≥ {contact.MIN_OVERLAP_PX} px → 3, else 2:", "",
          md_table(pd.crosstab(ct.split, ct.group, margins=True).reset_index()), "",
          "Brief expects 1100 / 101 / 277. The 2-vs-3 split **cannot be reproduced exactly** from these masks: "
          "no overlap-pixel or Obscuration threshold gives 101 (px<100 → 110; Obscuration≤0 → 87). "
          f"Also {((ct.contact == 1) & ~ct.overlap).sum()} contact cases show (near-)zero mask overlap, mostly scheme A (the canal may be painted over the molar). "
          "→ Treat derived groups 2/3 as approximate until we get the official group list."]

    # ---------------- DENTEX
    dx = audit_dentex()
    dx.to_csv(OUT / "audit_dentex.csv", index=False)
    L += ["", "## DENTEX (Zenodo)", "", md_table(dx.groupby(["zip", "subset"]).agg(n=("file", "size"),
          w_min=("w", "min"), w_max=("w", "max"), h_min=("h", "min"), h_max=("h", "max")).reset_index()), ""]
    for n, a in dentex_annotations().items():
        L.append(f"- `{n}`: {a['images']} images, {a['annotations']} boxes; " +
                 "; ".join(f"{k}: {v}" for k, v in a.items() if k.startswith("categor")))
    small = dx[(dx.w < 1000) | (dx.h < 500)]
    L.append("- validation_data has images only (no annotation JSON in the zip).")
    L.append(f"- {len(small)} images smaller than 1000×500 (all in: {sorted(small.subset.unique())}) → filter before use as real panoramics.")

    # ---------------- Clicks
    zc = dio.open_zip("toothfairy3_clicks")
    L += ["", "## ToothFairy3_Clicks", "", "Simulated clicks for the TF3 interactive challenge (not needed now): "
          + ", ".join(f"`{i.filename}` ({i.file_size / 1e6:.1f} MB)" for i in zc.infolist())]

    (OUT / "data_audit.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
